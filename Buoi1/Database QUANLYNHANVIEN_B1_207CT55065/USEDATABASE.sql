-- PHÉP KẾT JOIN

-- 1. Hãy cho biết mã nhân viên, tên nhân viên của những nhân viên đã tham gia
-- đề án với thời gian được phân công từ 20 trở lên. (INNER)
SELECT DISTINCT NV.MANV, NV.HONV + ' ' + NV.TENLOT + ' ' + NV.TENNV AS TENNV
FROM NHANVIEN NV
INNER JOIN PHANCONG PC ON NV.MANV = PC.MA_NVIEN
WHERE PC.THOIGIAN >= 20

-- 2. Hãy cho biết mã nhân viên, tên nhân viên, tên thân nhân và quan hệ thân
-- nhân của tất cả nhân viên, nếu nhân viên không có thân nhân thì tên thân
-- nhân và quan hệ thân nhân là Null (LEFT OUTER)
SELECT NV.MANV, NV.HONV + ' ' + NV.TENLOT + ' ' + NV.TENNV AS TENNV,
       TN.TENTN, TN.QUANHE
FROM NHANVIEN NV
LEFT OUTER JOIN THANNHAN TN ON NV.MANV = TN.MA_NVIEN

-- 3. Hãy cho biết mã nhân viên, tên nhân viên, số đề án, thời gian những nhân
-- viên đã tham gia đề án 'Tin hoc hoa', những nhân viên không có tham gia đề
-- án 'Tin hoc hoa' thì số đề án và thời gian là Null.
-- (LEFT OUTER, nhiều bảng, có điều kiện)
SELECT NV.MANV, NV.HONV + ' ' + NV.TENLOT + ' ' + NV.TENNV AS TENNV,
       X.SODA, X.THOIGIAN
FROM NHANVIEN NV
LEFT OUTER JOIN (
    SELECT PC.MA_NVIEN, PC.SODA, PC.THOIGIAN
    FROM PHANCONG PC
    INNER JOIN DEAN D ON PC.SODA = D.MADA
    WHERE D.TENDA = 'TIN HOC HOA'
) X ON NV.MANV = X.MA_NVIEN

-- KHUNG NHÌN

-- 4. Tạo View tên V_PB, hãy cho biết mã phòng, tên phòng ban của những phòng
-- ban có địa điểm phòng ban ở 'VUNG TAU' hoặc 'TP HCM'.
GO
CREATE VIEW V_PB AS
SELECT DISTINCT PB.MAPHG, PB.TENPHG
FROM PHONGBAN PB
INNER JOIN DIADIEM_PHG DP ON PB.MAPHG = DP.MAPHG
WHERE DP.DIADIEM IN ('VUNG TAU', 'TP HCM')
GO

SELECT * FROM V_PB

-- 5. Tạo View tên V_HCM, hãy cho biết mã nhân viên, tên nhân viên, ngày sinh
-- của những nhân viên có địa chỉ ở thành phố Hồ Chí Minh (TP HCM) hoặc có
-- lương lớn hơn 25000.
GO
CREATE VIEW V_HCM AS
SELECT MANV, HONV + ' ' + TENLOT + ' ' + TENNV AS TENNV, NGSINH
FROM NHANVIEN
WHERE DCHI LIKE '%TP HCM%' OR LUONG > 25000
GO

SELECT * FROM V_HCM

-- 6. Tạo View tên V_SLNV, hãy cho biết mã đề án, tên đề án, số lượng nhân
-- viên tham gia thực hiện từng đề án.
GO
CREATE VIEW V_SLNV AS
SELECT D.MADA, D.TENDA, COUNT(PC.MA_NVIEN) AS SLNV
FROM DEAN D
LEFT OUTER JOIN PHANCONG PC ON D.MADA = PC.SODA
GROUP BY D.MADA, D.TENDA
GO

SELECT * FROM V_SLNV
